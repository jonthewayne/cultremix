// Copies the registry ABI and bytecode out of the forge build so the app never reads
// contracts/out at runtime. Run after changing the contract:
//   (cd contracts && forge build) && bun run scripts/chain/export-abi.ts
//
// Writes:
//   convex/lib/chain/abi.ts            ABI only (bundled into Convex)
//   scripts/chain/registryArtifact.ts  ABI + creation bytecode (deploy scripts and the anvil run)
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const artifact = JSON.parse(
  readFileSync(new URL("contracts/out/CultRemixRegistry.sol/CultRemixRegistry.json", root), "utf8"),
) as { abi: Array<unknown>; bytecode: { object: string } };

const header = "// Generated by scripts/chain/export-abi.ts from the forge build. Do not edit.\n";
const abi = JSON.stringify(artifact.abi, null, 2);

writeFileSync(
  new URL("convex/lib/chain/abi.ts", root),
  `${header}export const registryAbi = ${abi} as const;\n`,
);
writeFileSync(
  new URL("scripts/chain/registryArtifact.ts", root),
  `${header}export { registryAbi } from "../../convex/lib/chain/abi";\n\n` +
    `export const registryBytecode =\n  "${artifact.bytecode.object}" as const;\n`,
);
console.log(`Exported ${artifact.abi.length} ABI entries and ${artifact.bytecode.object.length / 2 - 1} bytes of bytecode.`);
