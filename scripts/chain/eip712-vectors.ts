// Writes contracts/test/fixtures/eip712-vectors.json: EIP-712 test vectors that both the forge
// tests (Solidity) and tests/unit/eip712.test.ts (TypeScript) check against.
// Run: bun run scripts/chain/eip712-vectors.ts
//
// The keys are Anvil's public test accounts; they hold nothing on any real network.
import { writeFileSync } from "node:fs";
import { domainSeparator, hashStruct, hashTypedData, keccak256, toHex } from "viem";
import { privateKeyToAccount } from "viem/accounts";

const creatorKey = "0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d";
const backerKey = "0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a";
const creator = privateKeyToAccount(creatorKey);
const backer = privateKeyToAccount(backerKey);

const domain = {
  name: "CultRemixRegistry",
  version: "1",
  chainId: 10143,
  verifyingContract: "0x1111111111111111111111111111111111111111",
} as const;

const types = {
  RegisterWork: [
    { name: "workId", type: "bytes32" },
    { name: "family", type: "uint64" },
    { name: "expression", type: "uint32" },
    { name: "kind", type: "uint8" },
    { name: "parentId", type: "bytes32" },
    { name: "contentHash", type: "bytes32" },
    { name: "uriHash", type: "bytes32" },
    { name: "creator", type: "address" },
    { name: "deadline", type: "uint256" },
  ],
  Back: [
    { name: "workId", type: "bytes32" },
    { name: "backer", type: "address" },
    { name: "deadline", type: "uint256" },
  ],
} as const;

const registerWork = {
  workId: keccak256(toHex("cultremix:work:vector-child")),
  family: 101n,
  expression: 2,
  kind: 1,
  parentId: keccak256(toHex("cultremix:work:vector-root")),
  contentHash: "0x9f86d081884c7d659a2feaa0c55ad015a3bf4f1b2b0b822cd15d6c15b0f00a08",
  uriHash: keccak256(toHex("https://cultremix.com/cr/101-002")),
  creator: creator.address,
  deadline: 1790600000n,
} as const;

const back = {
  workId: registerWork.workId,
  backer: backer.address,
  deadline: 1790600000n,
} as const;

const registerDigest = hashTypedData({
  domain,
  types,
  primaryType: "RegisterWork",
  message: registerWork,
});
const backDigest = hashTypedData({ domain, types, primaryType: "Back", message: back });
const mainnetRegisterDigest = hashTypedData({
  domain: { ...domain, chainId: 143 },
  types,
  primaryType: "RegisterWork",
  message: registerWork,
});

const vectors = {
  note: "Generated by scripts/chain/eip712-vectors.ts. Keys are Anvil public test accounts.",
  domain,
  domainSeparator: domainSeparator({ domain }),
  registerWork: {
    privateKey: creatorKey,
    signer: creator.address,
    message: {
      ...registerWork,
      family: Number(registerWork.family),
      deadline: Number(registerWork.deadline),
    },
    structHash: hashStruct({ types, primaryType: "RegisterWork", data: registerWork }),
    digest: registerDigest,
    signature: await creator.signTypedData({
      domain,
      types,
      primaryType: "RegisterWork",
      message: registerWork,
    }),
    mainnetDigest: mainnetRegisterDigest,
  },
  back: {
    privateKey: backerKey,
    signer: backer.address,
    message: { ...back, deadline: Number(back.deadline) },
    structHash: hashStruct({ types, primaryType: "Back", data: back }),
    digest: backDigest,
    signature: await backer.signTypedData({ domain, types, primaryType: "Back", message: back }),
  },
};

const path = new URL("../../contracts/test/fixtures/eip712-vectors.json", import.meta.url);
writeFileSync(path, `${JSON.stringify(vectors, null, 2)}\n`);
console.log(`Wrote ${path.pathname}`);
